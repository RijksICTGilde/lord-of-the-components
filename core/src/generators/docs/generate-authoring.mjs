#!/usr/bin/env node
/**
 * Generate AUTHORING.md — a dense, LLM-optimised guide for building pages with
 * LOTC components (layout-first, NLDD-first). Generated from the code so it
 * never drifts: the component catalog comes from the registries, the spacing
 * tokens from layout.css. Curated bits (page skeleton, recipes, rules) live in
 * this script.
 *
 * Run:  node core/src/generators/docs/generate-authoring.mjs   ->  AUTHORING.md
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const CORE = JSON.parse(readFileSync(resolve(ROOT, "python/src/lord_of_the_components/registry.json"), "utf8"));
const NLDD = JSON.parse(readFileSync(resolve(ROOT, "packages/lotc-nldd/src/lotc_nldd/registry.json"), "utf8"));
const CHARTS = JSON.parse(readFileSync(resolve(ROOT, "packages/lotc-charts/src/lotc_charts/registry.json"), "utf8"));
const FORMS = JSON.parse(readFileSync(resolve(ROOT, "packages/lotc-forms/src/lotc_forms/registry.json"), "utf8"));
const LAYOUT_CSS = readFileSync(resolve(ROOT, "packages/lotc-layout/src/lotc_layout/static/lotc/layout/layout.css"), "utf8");

// ── spacing tokens (parsed from the config in layout.css) ──
const spaceTokens = [...LAYOUT_CSS.matchAll(/--lotc-space-([\w]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]);

// ── component indexes ──
const byName = new Map();
for (const c of CORE.components) byName.set(c.name, { ...c, source: "core" });
for (const c of NLDD.components) if (!byName.has(c.name)) byName.set(c.name, { ...c, source: "nldd" });
const all = [...byName.values()];

const LAYOUT_NAMES = new Set(
  all.filter((c) => c.category === "layout").map((c) => c.name),
);
const SYSTEM_HTML = new Set(all.filter((c) => c.category === "html").map((c) => c.name));

// ── helpers ──
const attrShort = (a) => {
  let s = `\`${a.name}\``;
  if (a.type === "enum") s += ` (${(a.enum_values || []).map((v) => v || "''").join("\\|")})`;
  else if (a.type === "boolean") s += ` (bool)`;
  if (a.owner) s += ` _[${a.owner}-only]_`;
  return s;
};
const compLine = (c) => {
  const attrs = (c.attributes || []).filter((a) => a.name !== "class");
  const shown = attrs.slice(0, 8).map(attrShort).join(", ");
  const more = attrs.length > 8 ? `, +${attrs.length - 8}` : "";
  const desc = (c.description || "").split("\n")[0];
  return `- \`<c-${c.name}>\`${desc ? ` — ${desc}` : ""}${shown ? `\n  <br>attrs: ${shown}${more}` : ""}`;
};

const CAT_LABEL = {
  actions: "Actions", content: "Content", forms: "Forms", "data-display": "Data display",
  navigation: "Navigation", feedback: "Feedback", layout: "Layout", html: "Basic HTML",
};

// group non-layout, non-html components by category
const catalog = {};
for (const c of all) {
  if (LAYOUT_NAMES.has(c.name) || SYSTEM_HTML.has(c.name)) continue;
  (catalog[c.category] = catalog[c.category] || []).push(c);
}
const catOrder = ["actions", "content", "forms", "data-display", "navigation", "feedback"];
const cats = [...new Set([...catOrder, ...Object.keys(catalog)])].filter((k) => catalog[k]);

// extended components (theme-owned extension attributes)
const extended = all.filter((c) => (c.attributes || []).some((a) => a.owner));

// ── assemble ──
const layoutComp = (n) => byName.get(n);
const L = [];
L.push(`<!-- GENERATED by core/src/generators/docs/generate-authoring.mjs — do not edit by hand. -->`);
L.push(`# Authoring pages with LOTC components\n`);
L.push(
  `A page is written **once** in \`<c-*>\` tags and rendered to a design system` +
    ` (NLDD-first here). This guide is generated from the code — ${all.length} components,` +
    ` ${LAYOUT_NAMES.size} layout primitives.\n`,
);

L.push(`## 1. Activate\n`);
L.push("```python");
L.push(`from lord_of_the_components import setup_components`);
L.push(`# layout layer + a design system (NLDD is the default target)`);
L.push(`setup_components(env, design_systems=["lotc-layout", "nldd"])`);
L.push("```");
L.push(
  `Rules: components resolve to the **first** active system that implements them;` +
    ` \`lotc-layout\` owns the structural primitives, \`nldd\` the visual components.` +
    ` Swap \`nldd\`→\`rvo\` to retarget the same markup.\n`,
);
L.push(
  `**Strictness (opt-in).** Silent authoring mistakes can be turned into loud errors:` +
    ` \`on_unknown_value="error"\` rejects an unrecognised value — an icon name absent` +
    ` from an active theme's set (\`verwijderen\` is RVO-only; NLDD has \`trash\`) or a` +
    ` literal outside an enum's set — with a suggestion. \`on_unknown_attribute="ignore"\`` +
    ` relaxes the (default) error on an undeclared attribute. \`debug=True\` implies` +
    ` \`on_unknown_value="error"\`. Set \`LOTC_STRICT=1\` in dev/CI to default it on` +
    ` without threading the argument (an explicit argument always wins).\n`,
);

L.push(`## 2. Page skeleton\n`);
L.push("```html");
L.push(`<c-page title="…" lang="nl" design-systems="lotc-layout nldd">`);
L.push(`  <c-app-shell width="16rem">`);
L.push(`    <template slot="header">   …c-header, c-bar…        </template>`);
L.push(`    <template slot="sidebar">  <c-sidenav>…</c-sidenav>  </template>`);
L.push(`    …main content…`);
L.push(`    <template slot="footer">   <c-footer>…</c-footer>    </template>`);
L.push(`  </c-app-shell>`);
L.push(`</c-page>`);
L.push("```");
L.push(`Named slots are filled with \`<template slot="name">…</template>\`; anything else is the default (main) content.\n`);
L.push(
  `**Page structure — mind the scroll model.** \`c-app-shell\` (layout layer) is a` +
    ` header/sidebar/main/footer grid that scrolls on the **window** — use it for a` +
    ` sidebar app frame. NLDD's own \`nldd-page\` is a **fixed-height (\`100dvh\`) shell`+
    ` with an internal scroll region** (\`overflow-y:auto; overscroll-behavior:contain\`):` +
    ` long content scrolls inside it, not the window, and a mouse wheel over it never` +
    ` reaches the window (window-based scroll-restoration breaks). For a normal` +
    ` window-scrolling page do **not** wrap in \`nldd-page\` — put the NLDD page regions` +
    ` (\`nldd-top-navigation-bar\`, \`nldd-sidebar-section\`, \`nldd-page-footer\`) directly` +
    ` in \`c-page\`'s body. \`c-page\` establishes NLDD's \`layout-container\` on \`<body>\`` +
    ` automatically — you do not set it by hand.\n`,
);
L.push(
  `**Max content width.** Cap it with \`width="…"\` on the NLDD page-region components` +
    ` (\`nldd-top-navigation-bar\`, \`nldd-sidebar-section\`, \`nldd-page-footer\`): it sets` +
    ` each region's \`--_max-width\`, so the content caps while the region background runs` +
    ` edge-to-edge (the number is the app's choice; NLDD ships no canonical value). For a` +
    ` plain content block outside those regions, \`<c-center max="76rem">\` is the` +
    ` theme-agnostic centred-column primitive. Note \`nldd-top-navigation-bar\` also needs` +
    ` \`logo-title\` (the organisation) beside \`website-title\` (the app), or its header` +
    ` grid collapses. And \`nldd-page-footer\` renders the **complete** footer (coat of` +
    ` arms included) — do not nest another footer component inside it.\n`,
);

L.push(`## 3. Layout primitives\n`);
L.push(`Structural, theme-agnostic, intrinsically responsive (no media queries). Compose freely.\n`);
L.push(`| Component | Purpose | Key attrs |`);
L.push(`| --- | --- | --- |`);
for (const n of ["app-shell", "layout", "grid", "auto-grid", "columns", "stack", "cluster", "bar", "sidebar", "switcher", "center", "cover", "box"]) {
  const c = layoutComp(n);
  if (!c) continue;
  const attrs = (c.attributes || []).filter((a) => a.name !== "class").map((a) => a.name).join(", ");
  L.push(`| \`<c-${n}>\` | ${(c.description || "").split("\n")[0].replace(/\|/g, "\\|")} | ${attrs} |`);
}
L.push(``);
L.push(`**Alignment — "N left, M right"** is \`c-bar\` (grid start/center/end):\n`);
L.push("```html");
L.push(`<c-bar gap="sm">`);
L.push(`  <template slot="start"><a>Overzicht</a><a>Apps</a><a>Code</a></template>`);
L.push(`  <template slot="end"><c-button type="primary" label="Nieuw"/></template>`);
L.push(`</c-bar>`);
L.push("```\n");

L.push(`## 4. Spacing config\n`);
L.push(
  `All layout spacing comes from one overridable token scale. \`gap="sm|md|lg|…"\`` +
    ` resolves to a token; a raw value (\`gap="1.25rem"\`) or \`0\`/\`none\` also work.` +
    ` Retune everything by redefining these in your own \`:root\`:\n`,
);
L.push(`| token | default |`);
L.push(`| --- | --- |`);
for (const [name, val] of spaceTokens) L.push(`| \`--lotc-space-${name}\` | \`${val}\` |`);
L.push(``);

L.push(`## 5. Extended components (theme-owned attributes)\n`);
L.push(
  `A component can carry base attributes (always valid) + extension attributes owned` +
    ` by a design system (valid only while that system is active; else a clear error).\n`,
);
for (const c of extended) {
  const owned = (c.attributes || []).filter((a) => a.owner).map((a) => `\`${a.name}\` (${a.owner})`).join(", ");
  L.push(`- \`<c-${c.name}>\` — theme-owned: ${owned}`);
}
L.push(``);

L.push(`## 6. Chart set (opt-in — Chart.js)\n`);
L.push(
  `An opt-in capability set: activate it alongside a design system and it loads` +
    ` Chart.js + draws request/limit lines. Only then do these resolve.\n`,
);
L.push("```python");
L.push(`setup_components(env, design_systems=["lotc-layout", "nldd", "lotc-charts"])`);
L.push("```");
for (const c of CHARTS.components) L.push(compLine(c));
L.push("```html");
L.push(`<c-line-chart id="cpu" title="CPU (millicores)" limit="500" request="250"`);
L.push(`              current="Current: 148m / 500m (30%)"`);
L.push(`              :data="{'labels': [...], 'datasets': [{'label':'CPU','data':[...],'borderColor':'#39870c','fill':true}]}"/>`);
L.push(`<c-gauge value="72" label="CPU" sublabel="2.9 / 4 cores"/>`);
L.push("```");
L.push(`Each chart needs a unique \`id\`. \`limit\`/\`request\` draw dashed threshold lines.\n`);

L.push(`## 7. Form set (opt-in — labelled fields + ARIA)\n`);
L.push(
  `An opt-in capability set of labelled form fields. Activate it **last**, after` +
    ` the visual theme. The same markup renders a theme-correct field (NLDD native` +
    ` \`nldd-form-field\`, RVO \`rvo-form-field\`) with the ARIA wiring guaranteed:` +
    ` label \`for\`/\`id\`, help + error via \`aria-describedby\`, \`aria-invalid\` on error.\n`,
);
L.push("```python");
L.push(`setup_components(env, design_systems=["lotc-layout", "nldd", "lotc-forms"])`);
L.push("```");
for (const c of FORMS.components) L.push(compLine(c));
L.push(``);
L.push(
  `Every field takes the same base — \`id\`, \`name\`, \`label\` (+ \`help\`, \`error\`,` +
    ` \`required\`, \`disabled\`). \`select-field\` renders` +
    ` NLDD's web-component combo-box by default; for a screen whose JS drives the list` +
    ` (value / new Option() / change), add \`native\` to keep a real \`<select>\`` +
    ` (native \`<option>\` children) under a theme skin.\n`,
);
L.push("```html");
L.push(`<form method="post">`);
L.push(`  <c-fieldset legend="Projectgegevens">`);
L.push(`    <c-text-input-field id="naam" name="naam" label="Projectnaam" help="…" required/>`);
L.push(`    <c-select-field id="afd" name="afd" label="Afdeling" placeholder="Kies…">`);
L.push(`      <c-option value="bz" label="Burgerzaken"/></c-select-field>`);
L.push(`    <c-radio-button-field id="zicht" label="Zichtbaarheid" error="Maak een keuze">`);
L.push(`      <c-radio name="zicht" value="pub" label="Openbaar"/></c-radio-button-field>`);
L.push(`  </c-fieldset>`);
L.push(`  <c-action-group align="end"><c-button type="primary" label="Opslaan"/></c-action-group>`);
L.push(`</form>`);
L.push("```\n");

L.push(`## 8. Component catalog\n`);
L.push(`Grouped by category. Enum attrs show their allowed values; \`[theme-only]\` marks extension attrs.\n`);
for (const cat of cats) {
  const comps = catalog[cat].sort((a, b) => a.name.localeCompare(b.name));
  L.push(`### ${CAT_LABEL[cat] || cat} (${comps.length})\n`);
  for (const c of comps) L.push(compLine(c));
  L.push(``);
}

// ── full page example (a real BG page, embedded from the fixture so it stays in sync) ──
const FULL_PAGE = readFileSync(resolve(ROOT, "tests/visual/fixtures/apps.html"), "utf8").trim();
L.push(`## 9. Full page example — BG "Software-catalogus"\n`);
L.push(
  `A complete page, 100% \`c-*\`: app-shell → header (status-bar + menu) + sidenav +` +
    ` metric grid + filter-bar + catalog cards + footer. Copy and adapt — this is the` +
    ` BG look. Two more complete pages live in \`tests/visual/fixtures/{zelf,bg-overzicht}.html\`` +
    ` (built by \`tests/visual/gen_{apps,zelf,bg_overzicht}.py\`).\n`,
);
L.push("```html");
L.push(FULL_PAGE);
L.push("```\n");

L.push(`## 10. Recipes\n`);
L.push(`**Card grid** (as many columns as fit):`);
L.push("```html");
L.push(`<c-auto-grid min="280px" gap="md">`);
L.push(`  <c-catalog-card icon="rectangle-stack" title="Paspoortaanvraag" subtitle="Burgerzaken"`);
L.push(`                  status="ok" status-type="success" maturity="goud" open-label="Open" href="/apps/x">`);
L.push(`    <c-tag type="default">service</c-tag><c-tag type="info">Rust</c-tag>`);
L.push(`  </c-catalog-card>`);
L.push(`</c-auto-grid>`);
L.push("```");
L.push(`**Metric row** (dashboard stats):`);
L.push("```html");
L.push(`<c-auto-grid min="220px" gap="md">`);
L.push(`  <c-metric icon="rectangle-stack" value="123" label="Applicaties" sub="in de catalogus"/>`);
L.push(`</c-auto-grid>`);
L.push("```");
L.push(`**Form:**`);
L.push("```html");
L.push(`<c-form>`);
L.push(`  <c-form-field label="Naam"><c-text-field placeholder="Vul je naam in"/></c-form-field>`);
L.push(`  <c-form-actions><c-button type="primary" label="Versturen"/></c-form-actions>`);
L.push(`</c-form>`);
L.push("```\n");

L.push(`## 11. Rules\n`);
L.push(`- **Slots**: named slots via \`<template slot="name">…</template>\`; default content is the rest.`);
L.push(`- **Enums are validated**: an out-of-set value (e.g. \`type="bogus"\`) errors (debug mode) with the allowed set.`);
L.push(`- **Theme-owned attrs** (§5) only work while their owner is active, else a clear error.`);
L.push(`- **Unknown component / attribute** → a hard error with a suggestion.`);
L.push(
  `- **Conditional attributes**: don't wrap a tag in \`{% if %}\` or put \`{% %}\`/\`{{ }}\`` +
    ` at an attribute position — the parser reads the braces as an attribute name. Use an` +
    ` expression attribute instead: \`:help="expr or none"\` (empty/None is omitted),` +
    ` \`:label="(a) if cond else (b)"\`, \`:required="expr"\`. For a whole dynamic bundle` +
    ` (htmx, arbitrary \`data-*\`/\`aria-*\`) use the spread \`:attrs="dict"\` — a flat` +
    ` \`{name: value}\` dict merged onto the element; \`None\`/\`''\` omits an entry.`,
);
L.push(
  `- **NLDD tables need \`columns\`**: \`<c-table>\` renders as a CSS-grid table under NLDD,` +
    ` so declare the columns (e.g. \`<c-table columns="1fr 1fr">\`) or every cell stacks in one` +
    ` column. RVO's native table needs none. \`<c-table-head>\` IS the header row (it renders` +
    ` \`<nldd-table-row slot="header">\`) — put \`<c-th>\` cells directly in it, don't nest a` +
    ` \`<c-table-row>\`.`,
);
L.push(
  `- **Named-slot-only components**: some NLDD components (e.g. \`c-icon-button\`,` +
    ` \`c-toolbar\`, \`c-toolbar-title\`) accept only named slots — put content in` +
    ` \`<template slot="…">\`, not as default children, which have nowhere to go and are` +
    ` dropped silently. (A tooltip on an icon-button goes in its \`popup\` slot, not as a child.)`,
);
L.push(`- One source, many themes: the same markup renders under \`nldd\` or \`rvo\`; the visual system swaps, the structure stays.`);
L.push(``);

writeFileSync(resolve(ROOT, "AUTHORING.md"), L.join("\n") + "\n", "utf8");
console.log(`wrote AUTHORING.md: ${all.length} components, ${LAYOUT_NAMES.size} layout, ${cats.length} catalog categories, ${spaceTokens.length} spacing tokens`);
